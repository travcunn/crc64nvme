// Command gen derives every carryless-multiply constant for CRC-64/NVME from the
// polynomial and writes internal/kconst/kconst.go and kconst_data.s.
//
// Mathematics (spec section 5): data is bit-reflected, so a 64x64 carryless
// multiply of reflected operands yields the reflected product times x. Each
// fold constant for a distance of n bits is therefore K(e) = bitrev64(x^e mod P)
// with e = n+63 for the low qword and e = n-1 for the high qword. The Barrett
// constants are bitrev65(x^128 div P) and bitrev65(P), truncated to 64 bits.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"sort"
)

const polyNormal uint64 = 0xad93d23594c93659 // P = x^64 + polyNormal

// poly128 is a polynomial of degree < 128 over GF(2).
type poly128 struct{ hi, lo uint64 }

// clmul64 returns the 128-bit carryless product of a and b.
func clmul64(a, b uint64) poly128 {
	var r poly128
	for i := 0; i < 64; i++ {
		if b>>uint(i)&1 == 1 {
			r.lo ^= a << uint(i)
			if i > 0 {
				r.hi ^= a >> uint(64-i)
			}
		}
	}
	return r
}

// mod reduces a (degree < 128) modulo P (degree 64), returning degree < 64.
func mod(a poly128) uint64 {
	for i := 63; i >= 0; i-- {
		if a.hi>>uint(i)&1 == 1 {
			// subtract P * x^i: the x^64 term clears a.hi bit i, polyNormal*x^i spans the words.
			a.hi ^= 1 << uint(i)
			a.lo ^= polyNormal << uint(i)
			if i > 0 {
				a.hi ^= polyNormal >> uint(64-i)
			}
		}
	}
	return a.lo
}

// xpow returns x^e mod P.
func xpow(e int) uint64 {
	r, b := uint64(1), uint64(2)
	for e > 0 {
		if e&1 == 1 {
			r = mod(clmul64(r, b))
		}
		b = mod(clmul64(b, b))
		e >>= 1
	}
	return r
}

// mu returns the low 64 bits of x^128 div P (the quotient has degree 64, so its
// x^64 coefficient is 1 and is not stored).
func mu() uint64 {
	var q uint64
	// Long division of x^128 by P. Track the dividend remainder r (degree < 65) as
	// top bit + 64-bit word while bringing down zeros.
	var r uint64 // coefficients below the current leading position
	top := uint64(1)
	for k := 64; k >= 0; k-- {
		if top == 1 {
			r ^= polyNormal
			if k < 64 {
				q |= 1 << uint(k)
			}
		}
		top = r >> 63
		r <<= 1
	}
	return q
}

func rev64(v uint64) uint64 {
	var r uint64
	for i := 0; i < 64; i++ {
		r = r<<1 | v&1
		v >>= 1
	}
	return r
}

// rev65 reflects a 65-bit value whose bit 64 is implicitly 1 and returns the low
// 64 bits of the reflection: bit 0 = 1, bit j = low64 bit (64-j).
func rev65(low64 uint64) uint64 {
	r := uint64(1)
	for j := 1; j < 64; j++ {
		r |= (low64 >> uint(64-j) & 1) << uint(j)
	}
	return r
}

const maxDist = 512 // bytes; covers blocks up to 8 ZMM accumulators

func main() {
	goOut := flag.String("go", "internal/kconst/kconst.go", "Go output")
	asmOut := flag.String("asm", "kconst_data.s", "assembly output")
	flag.Parse()

	exps := map[int]uint64{}
	k := func(e int) uint64 {
		v := rev64(xpow(e))
		exps[e] = v
		return v
	}
	type pair struct {
		d      int
		lo, hi uint64
	}
	var pairs []pair
	for d := 16; d <= maxDist; d += 16 {
		pairs = append(pairs, pair{d, k(8*d + 63), k(8*d - 1)})
	}
	k127 := k(127)
	muC := rev65(mu())
	polyC := rev65(polyNormal)

	var g bytes.Buffer
	fmt.Fprintf(&g, "// Copyright 2026 Travis Cunningham. Licensed under the Apache License, Version 2.0.\n\n")
	fmt.Fprintf(&g, "// Code generated by internal/gen. DO NOT EDIT.\n\n")
	fmt.Fprintf(&g, "// Package kconst holds the carryless-multiply constants for CRC-64/NVME.\n")
	fmt.Fprintf(&g, "// K(e) = bitrev64(x^e mod P). Pairs[i] is for a fold distance of d = 16*(i+1)\n")
	fmt.Fprintf(&g, "// bytes: {K(8d+63), K(8d-1)}. MU and POLY are bitrev65(x^128 div P) and\n")
	fmt.Fprintf(&g, "// bitrev65(P) truncated to 64 bits.\n")
	fmt.Fprintf(&g, "package kconst\n\n")
	fmt.Fprintf(&g, "const (\n\tMU uint64 = 0x%016x\n\tPOLY uint64 = 0x%016x\n\tK127 uint64 = 0x%016x\n)\n\n", muC, polyC, k127)
	fmt.Fprintf(&g, "var Pairs = [%d][2]uint64{\n", len(pairs))
	for _, p := range pairs {
		fmt.Fprintf(&g, "\t{0x%016x, 0x%016x}, // d=%d: K(%d), K(%d)\n", p.lo, p.hi, p.d, 8*p.d+63, 8*p.d-1)
	}
	fmt.Fprintf(&g, "}\n\n")
	keys := make([]int, 0, len(exps))
	for e := range exps {
		keys = append(keys, e)
	}
	sort.Ints(keys)
	fmt.Fprintf(&g, "var byExp = map[int]uint64{\n")
	for _, e := range keys {
		fmt.Fprintf(&g, "\t%d: 0x%016x,\n", e, exps[e])
	}
	fmt.Fprintf(&g, "}\n\n// K returns bitrev64(x^e mod P) if e was emitted.\nfunc K(e int) (uint64, bool) {\n\tv, ok := byExp[e]\n\treturn v, ok\n}\n")

	var a bytes.Buffer
	fmt.Fprintf(&a, "// Copyright 2026 Travis Cunningham. Licensed under the Apache License, Version 2.0.\n\n")
	fmt.Fprintf(&a, "// Code generated by internal/gen. DO NOT EDIT.\n\n")
	fmt.Fprintf(&a, "//go:build !purego && (amd64 || arm64)\n\n#include \"textflag.h\"\n\n")
	fmt.Fprintf(&a, "// foldK: entry i at offset 16*i is for distance d=16*(i+1) bytes: low qword K(8d+63), high qword K(8d-1).\n")
	for i, p := range pairs {
		fmt.Fprintf(&a, "DATA ·foldK+%d(SB)/8, $0x%016x // d=%d K(%d)\n", 16*i, p.lo, p.d, 8*p.d+63)
		fmt.Fprintf(&a, "DATA ·foldK+%d(SB)/8, $0x%016x // d=%d K(%d)\n", 16*i+8, p.hi, p.d, 8*p.d-1)
	}
	fmt.Fprintf(&a, "GLOBL ·foldK(SB), RODATA|NOPTR, $%d\n\n", 16*len(pairs))
	fmt.Fprintf(&a, "// reduceK: K127 at +0, MU at +16, POLY at +32, each in the low qword with a zero high qword.\n")
	fmt.Fprintf(&a, "DATA ·reduceK+0(SB)/8, $0x%016x\nDATA ·reduceK+8(SB)/8, $0\n", k127)
	fmt.Fprintf(&a, "DATA ·reduceK+16(SB)/8, $0x%016x\nDATA ·reduceK+24(SB)/8, $0\n", muC)
	fmt.Fprintf(&a, "DATA ·reduceK+32(SB)/8, $0x%016x\nDATA ·reduceK+40(SB)/8, $0\n", polyC)
	fmt.Fprintf(&a, "GLOBL ·reduceK(SB), RODATA|NOPTR, $48\n")

	src, err := format.Source(g.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*goOut, src, 0o644); err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*asmOut, a.Bytes(), 0o644); err != nil {
		log.Fatal(err)
	}
}
